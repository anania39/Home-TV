// Helper to escape HTML and JS strings safely







































function escapeHtml(str) {







































  if (!str) return "";







































  return String(str)







































    .replace(/&/g, "&amp;")







































    .replace(/</g, "&lt;")







































    .replace(/>/g, "&gt;")







































    .replace(/"/g, "&quot;")







































    .replace(/'/g, "&#039;");







































}















































































function escapeJs(str) {







































  if (!str) return "";







































  return String(str).replace(/'/g, "\\'").replace(/"/g, '\\"');







































}















































































